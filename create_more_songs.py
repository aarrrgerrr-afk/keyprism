"""Generate more recognizable demo MIDIs for the KeyPrism library."""
import mido
from mido import MidiFile, MidiTrack, Message, MetaMessage

TEMPO = 500000  # 120 BPM

def save(name, notes, tempo=TEMPO):
    mid = MidiFile(ticks_per_beat=480)
    track = MidiTrack()
    mid.tracks.append(track)
    track.append(MetaMessage('set_tempo', tempo=tempo, time=0))
    tick = 0
    for note, dur in notes:
        if note > 0:
            track.append(Message('note_on', note=note, velocity=80, time=tick))
            track.append(Message('note_off', note=note, velocity=0, time=int(dur * 480)))
        else:
            tick += int(dur * 480)
            continue
        tick = 0
    track.append(MetaMessage('end_of_track', time=0))
    mid.save(f'midi_files/{name}')
    print(f'  Created {name}')

